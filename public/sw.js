/* Service worker for the CRM PWA.

   Hand-written rather than generated by next-pwa/Workbox: this app is on Next 16
   with Turbopack, the wrappers habitually lag a major release, and the whole
   policy below is thirty lines of fetch handler. What matters here is not what
   is cached but what is NOT.

   NEVER CACHED, deliberately:
   - /api/* (this app's route handlers), the Django host and Supabase. A CRM
     showing yesterday's orders, a stale slot calendar or a stale BM list is
     worse than an error, and the auth token lives in localStorage, so a cached
     authenticated response would leak across logins on a shared store tablet.
   - HTML navigations, beyond an offline fallback. Which view a person may see
     is a permission decision made per session (app/App.tsx).

   CACHED: hashed build assets under /_next/static (immutable by construction —
   a new build produces new URLs) and the icons. That is what makes a relaunch
   on a tablet feel instant. */

const VERSION = 'md-crm-v1';
const SHELL = VERSION + '-shell';
const OFFLINE_URL = '/offline.html';

const PRECACHE = [OFFLINE_URL, '/icon-192.png', '/icon-512.png', '/icon-maskable-512.png'];

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(SHELL).then((c) => c.addAll(PRECACHE)));
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const names = await caches.keys();
    await Promise.all(names.filter((n) => !n.startsWith(VERSION)).map((n) => caches.delete(n)));
    await self.clients.claim();
  })());
});

/* The page asks for the update rather than the worker forcing it: a hard
   takeover mid-session would swap the bundle under someone filling in an audit
   form. app/PwaRegister.tsx prompts, then posts this. */
self.addEventListener('message', (event) => {
  if (event.data === 'skip-waiting') self.skipWaiting();
});

const isStatic = (url) => url.origin === self.location.origin
  && (url.pathname.startsWith('/_next/static/') || /\.(png|svg|ico|woff2?)$/.test(url.pathname));

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;

  const url = new URL(req.url);
  // Anything that carries live data, or leaves this origin, is left alone
  // entirely — no cache read, no cache write.
  if (url.origin !== self.location.origin) return;
  if (url.pathname.startsWith('/api/')) return;

  if (isStatic(url)) {
    event.respondWith((async () => {
      const hit = await caches.match(req);
      if (hit) return hit;
      const res = await fetch(req);
      if (res.ok) (await caches.open(SHELL)).put(req, res.clone());
      return res;
    })());
    return;
  }

  if (req.mode === 'navigate') {
    event.respondWith(
      fetch(req).catch(async () => (await caches.match(OFFLINE_URL)) || Response.error()),
    );
  }
});
